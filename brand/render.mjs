// node brand/render.mjs [filter] | --serve
// 1. Writes brand/logo/*.svg from brand/logo.mjs.
// 2. Writes the apps' generated logo data and favicons (apps/*/src/brand/logo-data.ts, apps/*/public/favicon.svg).
// 3. Renders every page in brand/source/*.html at deviceScaleFactor 2 into brand/kit/*.png,
//    and the logo files into brand/kit/logo/*.png (1024 px wide, transparent, whole-cell scale).
// `filter` renders only outputs whose name contains it. `--serve` keeps the static server up for editing.
import { createServer } from "node:http";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { extname, join, normalize } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";
import { logoSvg, logoData } from "./logo.mjs";

const brand = fileURLToPath(new URL(".", import.meta.url));
const repo = join(brand, "..");
const args = process.argv.slice(2);
const serveOnly = args.includes("--serve");
const filter = args.find((a) => !a.startsWith("--")) ?? "";

// ---- 1. SVGs ----
const svgs = {
  "mark.svg": logoSvg.mark(),
  "mark-mono.svg": logoSvg.markMono(),
  "tile.svg": logoSvg.tile(),
  "wordmark.svg": logoSvg.wordmark(),
  "wordmark-mono.svg": logoSvg.wordmarkMono(),
};
await mkdir(join(brand, "logo"), { recursive: true });
for (const [name, body] of Object.entries(svgs)) await writeFile(join(brand, "logo", name), body);

// ---- 2. App assets ----
const FIELD_TYPES = `// Generated by brand/render.mjs. Types for ascii-field.js.
export type SealFieldOptions = {
  shape?: "mark" | "none";
  progress?: number;
  auto?: boolean;
  markBox?: { x: number; y: number; size: number };
  cell?: number;
};
export type SealField = { setProgress(progress: number): void; redraw(): void; destroy(): void };
export function createSealField(host: HTMLElement, options?: SealFieldOptions): SealField;
`;
const data = `// Generated by brand/render.mjs from brand/logo.mjs. Do not edit by hand.\n` +
  `export const LOGO = ${JSON.stringify(logoData())} as const;\n`;
for (const app of ["magna-management", "reference-dapp"]) {
  await mkdir(join(repo, "apps", app, "src", "brand"), { recursive: true });
  await writeFile(join(repo, "apps", app, "src", "brand", "logo-data.ts"), data);
  await writeFile(join(repo, "apps", app, "public", "favicon.svg"), logoSvg.tile());
  const field = await readFile(join(brand, "source", "ascii-field.js"), "utf8");
  await writeFile(join(repo, "apps", app, "src", "brand", "ascii-field.js"),
    "// Generated by brand/render.mjs from brand/source/ascii-field.js. Do not edit by hand.\n" + field);
  await writeFile(join(repo, "apps", app, "src", "brand", "ascii-field.d.ts"), FIELD_TYPES);
}
console.info(`[brand] wrote ${Object.keys(svgs).length} SVGs and app logo data`);

// ---- 3. Static server over brand/ ----
const TYPES = { ".html": "text/html", ".css": "text/css", ".js": "text/javascript", ".mjs": "text/javascript",
  ".svg": "image/svg+xml", ".woff2": "font/woff2", ".png": "image/png" };
const server = createServer(async (req, res) => {
  const path = normalize(decodeURIComponent(new URL(req.url, "http://x").pathname)).replace(/^([/\\])+/, "");
  if (path.includes("..")) { res.writeHead(403).end(); return; }
  try {
    const body = await readFile(join(repo, path));
    res.writeHead(200, { "content-type": TYPES[extname(path)] ?? "application/octet-stream" }).end(body);
  } catch {
    res.writeHead(404).end("not found");
  }
});
await new Promise((r) => server.listen(serveOnly ? 4600 : 0, "127.0.0.1", r));
const base = `http://127.0.0.1:${server.address().port}`;
if (serveOnly) {
  console.info(`[brand] serving ${base}/brand/source/`);
} else {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1600, height: 900 }, deviceScaleFactor: 2 });

  const sheets = (await readdir(join(brand, "source"))).filter((f) => f.endsWith(".html") && f.includes(filter));
  await mkdir(join(brand, "kit", "logo"), { recursive: true });
  for (const file of sheets) {
    await page.goto(`${base}/brand/source/${file}`);
    await page.waitForSelector("body[data-ready='1']", { timeout: 15000 });
    const canvas = page.locator(".canvas");
    const out = join(brand, "kit", `magna-${file.replace(/\.html$/, "")}.png`);
    await canvas.screenshot({ path: out });
    console.info(`[brand] ${out.slice(repo.length + 1)}`);
  }

  // Logo PNGs: 1024 px wide (at whole-cell scale), transparent.
  for (const [name, body] of Object.entries(svgs)) {
    const out = join(brand, "kit", "logo", `magna-${name.replace(".svg", ".png")}`);
    if (!out.includes(filter)) continue;
    const vb = body.match(/viewBox="0 0 (\d+) (\d+)"/);
    const w = Number(vb[1]), h = Number(vb[2]);
    const scale = Math.floor(1024 / w);
    const tinted = body.includes("currentColor") ? body.replaceAll("currentColor", "#0C0C0B") : body;
    await page.setViewportSize({ width: w * scale, height: h * scale });
    await page.setContent(`<html><body style="margin:0;background:transparent">${tinted.replace("<svg ", `<svg width="${w * scale}" height="${h * scale}" `)}</body></html>`);
    await page.locator("svg").screenshot({ path: out, omitBackground: true, scale: "css" });
  }
  console.info("[brand] logo PNGs written");
  await browser.close();
  server.close();
}
