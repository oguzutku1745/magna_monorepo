#!/usr/bin/env node

// Simulates a WebAuthn authenticator with node WebCrypto and emits matching
// TS + Noir fixtures so the TS witness pipeline and the Noir circuit are
// tested against the same vectors. Run once and commit the outputs:
//   node ./scripts/gen-webauthn-fixtures.mjs
import { webcrypto, createHash } from "node:crypto";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(SCRIPT_DIR, "..");
const TS_OUT_PATH = resolve(ROOT, "packages/magna-wallet/src/webauthn/generated-webauthn-fixtures.ts");
const NOIR_OUT_PATH = resolve(ROOT, "contracts/magna-webauthn/src/generated_fixtures.nr");

if (
  !process.env.MAGNA_REGENERATE_WEBAUTHN_FIXTURES
  && existsSync(TS_OUT_PATH)
  && existsSync(NOIR_OUT_PATH)
) {
  console.log("fixtures already exist; set MAGNA_REGENERATE_WEBAUTHN_FIXTURES=1 to regenerate");
  process.exit(0);
}

const RP_ID = "localhost";
const ORIGIN = "http://localhost:5184";

const kp = await webcrypto.subtle.generateKey(
  { name: "ECDSA", namedCurve: "P-256" }, true, ["sign", "verify"],
);
const jwk = await webcrypto.subtle.exportKey("jwk", kp.publicKey);
const x = Buffer.from(jwk.x, "base64url");
const y = Buffer.from(jwk.y, "base64url");

const challenge = Buffer.from(webcrypto.getRandomValues(new Uint8Array(32)));
const clientData = `{"type":"webauthn.get","challenge":"${challenge.toString("base64url")}","origin":"${ORIGIN}","crossOrigin":false}`;
const clientDataJSON = Buffer.from(clientData, "utf8");

const rpIdHash = createHash("sha256").update(RP_ID).digest();
const flags = Buffer.from([0x05]); // UP | UV
const counter = Buffer.from([0, 0, 0, 0]);
const authenticatorData = Buffer.concat([rpIdHash, flags, counter]); // 37 bytes

const cdjHash = createHash("sha256").update(clientDataJSON).digest();
const signedPayload = Buffer.concat([authenticatorData, cdjHash]);

// Node WebCrypto ECDSA sign returns RAW r||s for P-256.
const rawSig = Buffer.from(await webcrypto.subtle.sign(
  { name: "ECDSA", hash: "SHA-256" }, kp.privateKey, signedPayload,
));
if (rawSig.length !== 64) {
  throw new Error(`expected raw P-256 signature length 64, got ${rawSig.length}`);
}

// Normalize to low-s so the vector is valid for Noir.
const P256_N = BigInt("0xffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551");
const r = rawSig.subarray(0, 32);
let sBig = BigInt("0x" + rawSig.subarray(32).toString("hex"));
if (sBig > P256_N >> 1n) sBig = P256_N - sBig;
const s = Buffer.from(sBig.toString(16).padStart(64, "0"), "hex");
const signature = Buffer.concat([r, s]);

const originIndex = clientData.indexOf('"origin":"');

const toList = (buf) => Array.from(buf).join(", ");

function writeFileWithParents(path, content) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content, "utf8");
}

writeFileWithParents(
  TS_OUT_PATH,
  `// AUTO-GENERATED by scripts/gen-webauthn-fixtures.mjs. DO NOT EDIT.
export const FIXTURE = {
  publicKeyX: Uint8Array.from([${toList(x)}]),
  publicKeyY: Uint8Array.from([${toList(y)}]),
  signatureRS: Uint8Array.from([${toList(signature)}]),
  authenticatorData: Uint8Array.from([${toList(authenticatorData)}]),
  clientDataJSON: Uint8Array.from([${toList(clientDataJSON)}]),
  challenge: Uint8Array.from([${toList(challenge)}]),
  originIndex: ${originIndex},
  origin: ${JSON.stringify(ORIGIN)},
  rpId: ${JSON.stringify(RP_ID)},
};
`,
);

writeFileWithParents(
  NOIR_OUT_PATH,
  `// AUTO-GENERATED by scripts/gen-webauthn-fixtures.mjs. DO NOT EDIT.
pub global GEN_PUBKEY_X: [u8; 32] = [${toList(x)}];
pub global GEN_PUBKEY_Y: [u8; 32] = [${toList(y)}];
pub global GEN_SIGNATURE: [u8; 64] = [${toList(signature)}];
pub global GEN_AD: [u8; 37] = [${toList(authenticatorData)}];
pub global GEN_CDJ: [u8; ${clientDataJSON.length}] = [${toList(clientDataJSON)}];
pub global GEN_CDJ_LEN: u32 = ${clientDataJSON.length};
pub global GEN_CHALLENGE: [u8; 32] = [${toList(challenge)}];
pub global GEN_ORIGIN_INDEX: u32 = ${originIndex};
`,
);
console.log("fixtures written");
